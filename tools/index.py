#!/usr/bin/env python3
"""Generate docs/INDEX.md: a deterministic map of stories, specs, ADRs, designs, QA, incidents.

    python tools/index.py          # write docs/INDEX.md
    python tools/index.py --check  # exit 1 if it is stale (CI)

Assistants and models see it in every stage bundle. Nothing here is mandatory content: a
project with no ADRs simply has an empty ADR section.
"""
import os
import re
import sys
from pathlib import Path

import miniyaml
import repowalk

ROOT = Path(__file__).resolve().parent.parent
HEADER = """<!-- Generated by tools/index.py. Do not edit; run `mise run index`. -->
# Index

Map of what exists. Search it before changing behaviour, then open what is relevant.
Not every story needs a spec, a design or an ADR: absence here is normal.
"""


def _sections(body):
    out, title, buf = {}, None, []
    for line in body.splitlines():
        if line.startswith("## "):
            if title is not None:
                out[title] = "\n".join(buf).strip()
            title, buf = line[3:].strip().lower(), []
        elif title is not None:
            buf.append(line)
    if title is not None:
        out[title] = "\n".join(buf).strip()
    return out


def _first_sentence(text, limit=140):
    text = re.sub(r"\s+", " ", re.sub(r"[`*_]", "", text)).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = (m.group(1) if m else text)
    return (s[: limit - 1] + "…") if len(s) > limit else s


def _cell(text):
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _table(head, rows):
    if not rows:
        return "None yet.\n"
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def _rel(root, path):
    return Path(os.path.relpath(path, root)).as_posix()


def _link(root, path, label):
    return f"[{label}]({_rel(root, path)})"


def build(root=ROOT):
    root = Path(root)
    arts = {"story": [], "adr": [], "design": [], "qa-report": [], "incident": [], "runbook": [], "release-notes": []}
    for path in repowalk.iter_markdown(root):
        if path.name == "INDEX.md":
            continue
        try:
            meta, body = miniyaml.split_frontmatter(path.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if meta and meta.get("type") in arts:
            arts[meta["type"]].append((path, meta, body))

    def by(key):
        return lambda a: str(a[1].get(key, ""))

    out = [HEADER]
    out.append("## Stories\n")
    rows = []
    for p, m, _ in sorted(arts["story"], key=by("id")):
        skip = m.get("skip") or []
        skip = ", ".join(skip) if isinstance(skip, list) else skip
        rows.append([_link(root, p, m.get("id")), m.get("status"), m.get("title"), skip])
    out.append(_table(["Story", "Status", "Title", "Skips"], rows))

    out.append("## Changes in flight (OpenSpec)\n")
    rows = []
    cdir = root / "openspec" / "changes"
    if cdir.is_dir():
        for d in sorted(x for x in cdir.iterdir() if x.is_dir() and x.name != "archive"):
            why = ""
            prop = d / "proposal.md"
            if prop.exists():
                why = _first_sentence(_sections(prop.read_text(encoding="utf-8")).get("why", ""))
            rows.append([f"[{d.name}](openspec/changes/{d.name}/)", why])
    out.append(_table(["Change", "Why"], rows))

    out.append("## Current specs (OpenSpec)\n")
    rows = []
    sdir = root / "openspec" / "specs"
    if sdir.is_dir():
        for spec in sorted(sdir.glob("*/spec.md")):
            reqs = re.findall(r"^###\s+Requirement:\s*(.+)$", spec.read_text(encoding="utf-8"), re.M)
            rows.append([f"[{spec.parent.name}]({_rel(root, spec)})", "; ".join(r.strip() for r in reqs)])
    out.append(_table(["Capability", "Requirements"], rows))

    out.append("## Decisions (ADR)\n")
    rows = []
    for p, m, body in sorted(arts["adr"], key=by("id")):
        rows.append([_link(root, p, m.get("id")), m.get("status"), m.get("story"), m.get("title"),
                     _first_sentence(_sections(body).get("decision", ""))])
    out.append(_table(["ADR", "Status", "Story", "Title", "Decision"], rows))

    out.append("## Designs\n")
    rows = [[_link(root, p, m.get("story")), m.get("status"), m.get("title")] for p, m, _ in sorted(arts["design"], key=by("story"))]
    out.append(_table(["Story", "Status", "Title"], rows))

    out.append("## QA reports\n")
    rows = [[_link(root, p, m.get("story")), m.get("verdict"), m.get("date")] for p, m, _ in sorted(arts["qa-report"], key=by("story"))]
    out.append(_table(["Story", "Verdict", "Date"], rows))

    out.append("## Incidents and runbooks\n")
    rows = [[_link(root, p, m.get("id")), "incident", m.get("severity"), m.get("status"), m.get("title")]
            for p, m, _ in sorted(arts["incident"], key=by("id"))]
    rows += [[_link(root, p, m.get("id")), "runbook", "", "", m.get("title")]
             for p, m, _ in sorted(arts["runbook"], key=by("id"))]
    out.append(_table(["Id", "Kind", "Severity", "Status", "Title"], rows))
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv):
    target = ROOT / "docs" / "INDEX.md"
    text = build(ROOT)
    if "--check" in argv:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print("docs/INDEX.md is stale: run `mise run index` and commit it.", file=sys.stderr)
            return 1
        print("index: up to date")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {_rel(ROOT, target)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
